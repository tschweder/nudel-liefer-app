/**
 * The generic offline page served by the service worker when a driver page cannot be loaded
 * (NUD-080). Static HTML with the texts of all four locales (from messages/*.json, key group
 * `pwa.offline`); a tiny script shows the language of the URL prefix. No personal data.
 */

import { BASE_PATH, withBasePath } from "../../src/lib/base-path";

export const OFFLINE_LOCALES = ["de", "zh-Hans", "zh-Hant-HK", "zh-Hant-TW"] as const;
export type OfflineLocale = (typeof OFFLINE_LOCALES)[number];
export type OfflineTexts = { title: string; text: string; retry: string };

const escapeHtml = (value: string) =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

/** Name of the script the offline page loads; precached next to it. */
export const OFFLINE_SCRIPT_PATH = withBasePath("/offline.js");

/**
 * The script of the offline page. It is a file of its own, not inline, because the Content
 * Security Policy of static files has no `'unsafe-inline'` (NUD-110); the reload button is wired
 * here for the same reason (no `onclick` attribute).
 *
 * The base path is baked in at build time (the page is generated by `scripts/build-pwa.ts`), so the
 * generated code is byte-for-byte the previous one when the app is served at the origin root.
 */
export function buildOfflineScript(): string {
  const prefix = JSON.stringify(BASE_PATH);
  const launchPath = JSON.stringify(`${BASE_PATH}/driver`);
  const localeRoot = JSON.stringify(`${BASE_PATH}/`);
  return `(function () {
  var basePath = ${prefix};
  var buttons = document.querySelectorAll("button[data-reload]");
  for (var b = 0; b < buttons.length; b++) buttons[b].addEventListener("click", function () { location.reload(); });
  var wanted = location.pathname.slice(basePath.length).split("/")[1];
  var sections = document.querySelectorAll("section[data-locale]");
  function known(l) {
    for (var k = 0; k < sections.length; k++) if (sections[k].getAttribute("data-locale") === l) return true;
    return false;
  }
  // Start URL of the installed app (/driver?source=pwa, NUD-106) while offline: forward to the
  // driver's last-used language (NEXT_LOCALE cookie, set by the language switcher and the
  // login) so the worker answers with the offline shell of that language; German if unknown.
  if (wanted === "driver" && location.pathname.replace(/\\/+$/, "") === ${launchPath}) {
    var cookie = /(?:^|; )NEXT_LOCALE=([^;]*)/.exec(document.cookie);
    var lang = "de";
    try { if (cookie && known(decodeURIComponent(cookie[1]))) lang = decodeURIComponent(cookie[1]); } catch (e) {}
    location.replace(${localeRoot} + lang + "/driver" + location.search);
    return;
  }
  var shown = false;
  for (var i = 0; i < sections.length; i++) {
    if (sections[i].getAttribute("data-locale") === wanted) { sections[i].hidden = false; shown = true; }
  }
  if (!shown) sections[0].hidden = false;
  document.documentElement.lang = shown ? wanted : "de";
})();
`;
}

export function buildOfflineHtml(
  texts: Record<OfflineLocale, OfflineTexts>,
  themeColor: string,
): string {
  const sections = OFFLINE_LOCALES.map((locale) => {
    const t = texts[locale];
    return `    <section lang="${locale}" data-locale="${locale}" hidden>
      <svg class="icon" viewBox="0 0 24 24" width="48" height="48" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m2 2 20 20"/><path d="M8.5 16.5a5 5 0 0 1 7 0"/><path d="M2 8.8a15 15 0 0 1 4.2-2.6"/><path d="M10.7 5.1A15 15 0 0 1 22 8.8"/><path d="M5 12.9a10 10 0 0 1 5.2-2.7"/><path d="M13.8 10.2a10 10 0 0 1 5.2 2.7"/><path d="M12 20h.01"/></svg>
      <h1>${escapeHtml(t.title)}</h1>
      <p>${escapeHtml(t.text)}</p>
      <button type="button" data-reload>${escapeHtml(t.retry)}</button>
    </section>`;
  }).join("\n");
  return `<!doctype html>
<html lang="de">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="theme-color" content="${themeColor}" />
    <meta name="robots" content="noindex" />
    <title>${escapeHtml(texts.de.title)}</title>
    <style>
      :root { color-scheme: light dark; }
      body { margin: 0; min-height: 100dvh; display: grid; place-items: end center; padding: 16px 16px 15vh; box-sizing: border-box;
        font: 18px/1.5 system-ui, "PingFang SC", "PingFang HK", "PingFang TC", "Noto Sans SC", "Noto Sans HK", "Noto Sans TC", "Microsoft YaHei", "Microsoft JhengHei", sans-serif; }
      main { max-width: 24rem; text-align: center; }
      .icon { display: block; margin: 0 auto 1rem; }
      h1 { font-size: 1.5rem; margin: 0 0 .5rem; }
      p { margin: 0 0 1.5rem; }
      button { min-height: 48px; min-width: 48px; padding: 0 1.5rem; font: inherit; font-weight: 600; border: 0; border-radius: 8px; color: #fff; background: ${themeColor}; }
    </style>
  </head>
  <body>
    <main>
${sections}
    </main>
    <script src="${OFFLINE_SCRIPT_PATH}"></script>
  </body>
</html>
`;
}
